type FileKind =
  | (typeof NAMES)[keyof typeof NAMES]
  | (typeof EXTENSIONS)[keyof typeof EXTENSIONS]
  | (typeof PREFIXES)[number][1]
  | "file";
type FolderKind = (typeof FOLDERS)[keyof typeof FOLDERS];

/** An icon of the theme: `folder`, `folder-src-open`, `rust`, … */
export type FileIconId = FileKind | "folder" | "folder-open" | `folder-${FolderKind}` | `folder-${FolderKind}-open`;

// Maps, not the objects: a name like `constructor` must not find anything.
const byName = new Map<string, FileKind>(Object.entries(NAMES));
const byExtension = new Map<string, FileKind>(Object.entries(EXTENSIONS));
const folderByName = new Map<string, FolderKind>(Object.entries(FOLDERS));

/** The icon of a file by its name (not its path). */
export function fileIcon(name: string): FileIconId {
  const lower = name.toLowerCase();
  const named = byName.get(lower);
  if (named) return named;
  for (const [prefix, kind] of PREFIXES) {
    if (lower.startsWith(prefix) && !/[a-z0-9]/.test(lower.charAt(prefix.length))) return kind;
  }
  for (let dot = lower.indexOf(".", 1); dot >= 0; dot = lower.indexOf(".", dot + 1)) {
    const kind = byExtension.get(lower.slice(dot + 1));
    if (kind) return kind;
  }
  return "file";
}

/** The icon of a folder by its name; a chain of folders (`crates/vet-core/src`) takes its last one's. */
export function folderIcon(name: string, open: boolean): FileIconId {
  const kind = folderByName.get(basename(name).toLowerCase());
  return kind ? `folder-${kind}${open ? "-open" : ""}` : open ? "folder-open" : "folder";
}
